#!/usr/bin/env python
"""Off-policy mismatch probe for the FH-DCMPO TD(lambda) cost target.

Question this instrument answers (diagnosis only -- it changes nothing about training):
**are the L=64 TD(lambda) cost windows realized under behavior policies too different from the
current policy for the cost critic's tail to be calibrated online?**

The replay buffer stores no behavior log-probs, and they cannot be reconstructed exactly (the
policy changes every iteration; checkpoints exist every 5k). What checkpoints DO allow is an
exact emulation: roll out checkpoint ``pi_old`` (the behavior policy a replay transition of age
``delta`` was generated by), then evaluate everything under checkpoint ``pi_new`` (the current
policy). Both densities are exact -- nothing is faked.

Phases (cached to disk between them):

1. ``rollout``  -- roll out every checkpoint stochastically, recording obs/actions/log-probs/costs.
2. ``mismatch`` -- per-depth ``log_ratio_j = log pi_new(a_j|s_j) - log pi_behavior(a_j|s_j)``
   along 64-step windows, cumulative products, ESS, extreme-ratio fractions, and the correlation
   with window cost (report section 2 of the investigation).
3. ``calib``    -- pi_new's cost critic evaluated on states/actions/realized cost-to-go from each
   age bucket (report section 3: does calibration degrade specifically on old-policy data?).
4. ``control``  -- retrain ONLY the cost critic from the pi_new checkpoint, same TD(lambda) rule,
   same update count, on (a) an age-mixed buffer emulating full replay vs (b) recent-only data;
   evaluate both on held-out pi_new rollouts (report section 4: the causal control).

Usage (defaults match the live a2_lag_cc4 run):
    CUDA_VISIBLE_DEVICES=1 python scripts/analysis/offpolicy_mismatch_probe.py \
        --run_dir logs/safety_gymnasium/SafetyPointGoal1-v0/FHDCMPO/20260819_080249 \
        --config config/safety_gymnasium_fhdcmpo_a2_lag_cc4_60k.yaml --phase all
"""

from __future__ import annotations

import argparse
import json
import math
